-- Create Permission Enum
-- Permissions style 'action:resource:[optional]modifier', should just be strings tho ...
-- | =================================== |
-- | Modifider in use:                   |
-- | self    : resources owned by a user |
-- | friends : friends can see this data |
-- | global  : open to the public        |
-- | =================================== |
