-- Create the auth hook function
create or replace function rbac.custom_access_token_hook(event jsonb)
returns jsonb as $$
  declare
    claims jsonb;
    user_roles jsonb;
  begin
    -- Aggregate all roles for the user into a JSONB array
    select jsonb_agg(role) into user_roles from rbac.user_roles where user_id = (event->>'user_id')::uuid;

    claims := event->'claims';

    if user_roles is not null then
      -- Set the nested roles array in claims under user_metadata
      claims := jsonb_set(claims, '{user_metadata,roles}', user_roles, true);
    end if;

    -- Update the 'claims' field in the original event
    event := jsonb_set(event, '{claims}', claims);

    -- Return the updated event JSONB
    return event;
  end;
$$ language plpgsql set search_path = '';


grant execute
  on function rbac.custom_access_token_hook
  to supabase_auth_admin;
revoke execute
  on function rbac.custom_access_token_hook
  from authenticated, anon, public;
grant all
  on table rbac.user_roles
  to supabase_auth_admin;
revoke all
  on table rbac.user_roles
  from authenticated, anon, public;
create policy "Allow auth admin to read user roles" ON rbac.user_roles
  as permissive for select
  to supabase_auth_admin
  using (true);

create or replace function rbac.authorize(
  requested_permission rbac.permissions
)
returns boolean as $$
begin
  return exists (
    select 1
      from rbac.user_roles ur
      join rbac.role_permissions rp on ur.role = rp.role
     where ur.user_id = auth.uid()
       and rp.permission = requested_permission
  );
end;
$$ language plpgsql set search_path = '';
