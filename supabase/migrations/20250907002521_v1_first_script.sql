end $$;

do $$
begin
create table if not exists rbac.user_roles (
  -- id        bigint generated by default as identity primary key,
  user_id   uuid references auth.users on delete cascade not null,
  role      text references rbac.roles(role) on delete cascade not null,
  primary key (user_id, role)
  -- unique (user_id, role)
);
comment on table rbac.user_roles is 'Application roles for each user.';
end $$;

do $$
begin
create table if not exists rbac.role_permissions (
  -- id bigint generated by default as identity primary key,
  role text references rbac.roles(role) on delete cascade not null,
  permission text references rbac.permissions(permission) on delete cascade not null,
  primary key (role, permission)
);
comment on table rbac.role_permissions is 'Application permissions for each role.';
end $$;
