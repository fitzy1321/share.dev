create or replace function rbac.make_user_role()
returns trigger as $$
begin
  insert into rbac.user_roles (user_id, role)
  values (new.id, 'user');
  return new;
end;
$$ language plpgsql set search_path = '';

drop trigger if exists make_user_role on auth.users;
create trigger make_user_role
  after insert on auth.users
  for each row execute procedure rbac.make_user_role();
