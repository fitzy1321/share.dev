begin
create table if not exists rbac.permissions (
  id bigint generated by default as identity primary key,
  permission text UNIQUE NOT NULL
);
comment on table rbac.permissions is 'RBAC Permissions for Application.';
insert into rbac.permissions (permission) values
  -- Posts
  ('create:post'),
  ('read:post'),
  ('update:post:self'),
  ('delete:post:self'),
  ('delete:post:any'),
